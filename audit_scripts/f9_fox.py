"""Alexander ideal of the two ch=12 spheres filed as "matches the unknot", computed by hand-rolled Fox
calculus from the repository's stored two-generator presentations (independent of the repo's ideal code).
Generators map to t^(+-1) as forced by the relators.  For a knot group the ideal E_1 is generated by the
entries of one column of the Jacobian (the column of a generator that maps to t^(+-1))."""
import re, sympy as sp
t = sp.Symbol('t')
PRES = {
 "amb2": ["x2^-1 x1^-1 x2^-1 x1^-1 x2^-1 x1^-1", "x2^-1 x1^-1 x2^-1 x1 x2 x1^-1 x2^-1 x1^-1 x2 x1",
          "x2^-3 x1^-2 x2^-1 x1^-2 x2^-1 x1^2 x2 x1^2 x2 x1^2 x2^2 x1 x2 x1^-1 x2^-1 x1^-2 x2^-1 x1^-2"],
 "amb9": ["x2^-1 x1^-1 x2^-1 x1^-1 x2 x1 x2 x1", "x2^-2 x1^-1 x2^2 x1^2 x2 x1^-2", "x2^-2 x1^-1 x2 x1^2 x2^-1 x1^-1 x2 x1"],
}
def parse(s):
    w = []
    for tok in s.split():
        m = re.fullmatch(r"x(\d)(?:\^(-?\d+))?", tok); g = int(m.group(1)); e = int(m.group(2) or 1)
        w += [g if e > 0 else -g] * abs(e)
    return w
def fox(w, gen, img):
    """d w / d x_gen, evaluated in Z[t, 1/t]"""
    acc = sp.Integer(0); pre = sp.Integer(1)
    for l in w:
        g = abs(l)
        if l > 0:
            if g == gen: acc += pre
            pre *= img[g]
        else:
            pre *= 1 / img[g]
            if g == gen: acc -= pre
    return sp.expand(acc)
for tag, rels in PRES.items():
    W = [parse(r) for r in rels]
    # exponent sums decide the images: a*e1 + b*e2 = 0 for every relator
    sums = [(sum(1 if l == 1 else -1 if l == -1 else 0 for l in w), sum(1 if l == 2 else -1 if l == -2 else 0 for l in w)) for w in W]
    img = {1: t, 2: t} if all(a + b == 0 for a, b in sums) else {1: t, 2: 1 / t}
    assert all((a + b == 0) if img[2] == t else (a - b == 0) for a, b in sums), sums
    col = [fox(w, 1, img) for w in W]
    polys = [sp.Poly(sp.expand(c * t**40), t) for c in col]
    print(tag, 'x2 ->', img[2])
    for c in col: print('   d r / d x1 =', sp.factor(c))
    # ideal generated by col in Z[t,1/t]: report content gcd and the gcd mod 3
