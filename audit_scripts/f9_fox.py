    ints = [int(c) for c in col if c.is_Integer and c != 0]
    print('   integer entries:', ints)
    for p in (2, 3, 5, 7):
        gp = sp.Poly(0, t, modulus=p)
        for q in polys: gp = sp.gcd(gp, sp.Poly(q.as_expr(), t, modulus=p))
        print(f'   gcd of the column mod {p}:', gp.as_expr())
